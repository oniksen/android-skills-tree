import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const contentDir = path.join(root, "content", "study-materials");
const outPath = path.join(root, "src", "features", "study", "study-materials.generated.ts");

const grades = fs.readdirSync(contentDir, { withFileTypes: true });
const entries = [];

for (const gradeEntry of grades) {
  if (!gradeEntry.isDirectory()) continue;
  const grade = gradeEntry.name;
  const gradeDir = path.join(contentDir, grade);
  const files = fs.readdirSync(gradeDir).filter((f) => f.endsWith(".md"));
  for (const file of files) {
    const id = file.replace(/\.md$/, "");
    const raw = fs.readFileSync(path.join(gradeDir, file), "utf8");
    const titleMatch = raw.match(/^#\s+(.+)$/m);
    const title = titleMatch ? titleMatch[1].trim() : id;
    entries.push({ id, title, grade, categoryId: id, content: raw });
  }
}

entries.sort((a, b) => (a.grade + a.id).localeCompare(b.grade + b.id));

const lines = [];
lines.push("// Auto-generated by scripts/generate-study-materials-registry.mjs");
lines.push("// Do not edit manually. Run `npm run generate:materials` to regenerate.");
lines.push("");
lines.push('import type { StudyMaterialContent } from "./study-material";');
lines.push("");
lines.push("export const STUDY_MATERIALS: Record<string, StudyMaterialContent> = {");
for (const e of entries) {
  lines.push(`  ${JSON.stringify(e.id)}: {`);
  lines.push(`    id: ${JSON.stringify(e.id)},`);
  lines.push(`    title: ${JSON.stringify(e.title)},`);
  lines.push(`    grade: ${JSON.stringify(e.grade)},`);
  lines.push(`    categoryId: ${JSON.stringify(e.categoryId)},`);
  lines.push(`    content: ${JSON.stringify(e.content)},`);
  lines.push("  },");
}
lines.push("};");
lines.push("");

fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`generated ${entries.length} materials -> ${outPath}`);